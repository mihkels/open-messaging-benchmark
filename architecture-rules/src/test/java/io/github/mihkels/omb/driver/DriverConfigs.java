package io.github.mihkels.omb.driver;

import java.nio.file.Path;

/** Minimal test stub matching {@code driver-api}'s {@code DriverConfigs} FQN. */
public final class DriverConfigs {
    private DriverConfigs() {}

    public static <T> T read(Path file, Class<T> type) {
        try {
            return type.getDeclaredConstructor().newInstance();
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException(e);
        }
    }
}
