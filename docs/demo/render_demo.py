"""Render the landing page demo from a recorded quickstart run.

Reads quickstart-run.log (coordinator output) and quickstart-result.json (the result file) from
this directory and writes two Jinja partials used by overrides/home.html:

  overrides/partials/omb-demo-terminal.html   terminal transcript replayed by home.js
  overrides/partials/omb-demo-charts.html     rate and latency charts as inline SVG

Usage, from the repository root: python3 docs/demo/render_demo.py
"""

import html
import json
import math
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
PARTIALS = ROOT / "overrides" / "partials"

HEADER = """{#-
  Licensed under the Apache License, Version 2.0 (the "License");
  you may not use this file except in compliance with the License.
  You may obtain a copy of the License at

  http://www.apache.org/licenses/LICENSE-2.0

  Unless required by applicable law or agreed to in writing, software
  distributed under the License is distributed on an "AS IS" BASIS,
  WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
  See the License for the specific language governing permissions and
  limitations under the License.

  Generated by docs/demo/render_demo.py. Do not edit.
-#}
"""

COMMANDS = [
    "cd local-test && docker compose up -d",
]
COMPOSE_OUTPUT = [
    " ✔ Container kafka         Started",
    " ✔ Container omb-worker-1  Started",
    " ✔ Container omb-worker-2  Started",
    " ✔ Container omb-driver    Started",
]
RUN_COMMAND = [
    "docker exec -it omb-driver bash -lc \\",
    "  'bin/benchmark --drivers /drivers/kafka.yaml \\",
    "     --workers http://omb-worker-1:8080,http://omb-worker-2:8080 \\",
    "     -o first-result.json /workloads/simple.yaml'",
]

# Coordinator log messages kept in the transcript, in order of appearance.
KEEP = re.compile(
    r"^(--------------- WORKLOAD|Created \d+ (topics|consumers|producers)|All consumers are ready"
    r"|----- Starting|Pub rate|----- Aggregated|Writing test result)"
)
LOG_PREFIX = re.compile(r"^\S+ \[[^\]]+\] \w+ \S+ - ")


def transcript_lines():
    out = []
    for c in COMMANDS:
        out.append(("cmd", c, 0))
    for o in COMPOSE_OUTPUT:
        out.append(("ok", o, 140))
    for i, c in enumerate(RUN_COMMAND):
        out.append(("cmd" if i == 0 else "cmd cont", c, 0))
    for raw in (HERE / "quickstart-run.log").read_text().splitlines():
        m = LOG_PREFIX.match(raw)
        if not m:
            continue
        msg = raw[m.end():]
        if not KEEP.match(msg):
            continue
        # Keep the terminal readable: drop the publish-delay tail of statistics lines.
        msg = msg.split(" | Pub Delay")[0].rstrip()
        if msg.startswith("Pub rate"):
            out.append(("", msg, 160))
        elif msg.startswith("----- Aggregated"):
            out.append(("hl", msg, 260))
        elif msg.startswith("Writing"):
            out.append(("ok", msg, 300))
        else:
            out.append(("dim", msg, 260))
    return out


def render_terminal():
    rows = []
    for cls, text, delay in transcript_lines():
        classes = ("l " + cls).strip()
        rows.append(f'<span class="{classes}" data-d="{delay}">{html.escape(text)}</span>')
    # No newlines between lines: each line is a block element inside <pre>.
    body = "".join(rows)
    return HEADER + f"""<div class="omb-term">
  <div class="omb-term__bar">
    <span class="omb-term__dots" aria-hidden="true"><i></i><i></i><i></i></span>
    <span>quickstart &middot; Kafka 4.4 &middot; 2 workers</span>
    <button class="omb-term__replay" type="button" data-omb-replay>Replay</button>
  </div>
  <pre class="omb-term__body" data-omb-term tabindex="0" aria-label="Quickstart terminal output">{body}</pre>
  <p class="omb-term__note">Recorded quickstart run on a laptop with Docker; timestamps, logger names and the publish-delay columns removed. Example output, not a benchmark result.</p>
</div>
"""


# ---------- charts ----------

W, H = 400, 220
ML, MR, MT, MB = 44, 12, 14, 34


def fmt(v):
    if v >= 100:
        return f"{v:.0f}"
    if v >= 10:
        return f"{v:.1f}"
    return f"{v:.2f}"


def nice_ceil(v):
    exp = 10 ** math.floor(math.log10(v))
    for m in (1, 2, 2.5, 5, 10):
        if m * exp >= v:
            return m * exp
    return 10 * exp


def rate_chart(result):
    pub = result["publishRate"]
    con = result["consumeRate"]
    n = len(pub)
    ymax = nice_ceil(max(pub + con) * 1.1)
    pw, ph = W - ML - MR, H - MT - MB

    def x(i):
        return ML + (i / (n - 1)) * pw

    def y(v):
        return MT + ph - (v / ymax) * ph

    parts = ['<g class="grid">']
    ticks = [ymax * k / 4 for k in range(5)]
    for t in ticks:
        parts.append(f'<line x1="{ML}" x2="{W - MR}" y1="{y(t):.1f}" y2="{y(t):.1f}"/>')
    parts.append("</g><g class=\"axis\">")
    for t in ticks:
        parts.append(f'<text x="{ML - 8}" y="{y(t) + 3:.1f}" text-anchor="end">{t:.0f}</text>')
    for i in range(n):
        sec = (i + 1) * 10
        if sec % 30 == 0:
            parts.append(f'<text x="{x(i):.1f}" y="{H - MB + 16}" text-anchor="middle">{sec}s</text>')
    parts.append(f'<text class="title" x="{ML}" y="{H - 2}">time into measured phase</text>')
    parts.append("</g>")
    for cls, data, extra in (("s1", pub, ""), ("s2", con, ' stroke-dasharray="5 4"')):
        d = " ".join(f"{'M' if i == 0 else 'L'}{x(i):.1f},{y(v):.1f}" for i, v in enumerate(data))
        parts.append(f'<path class="line {cls}" d="{d}"{extra}/>')
    for i in range(n):
        sec = (i + 1) * 10
        tip = f"{sec}s: publish {pub[i]:.1f} msg/s, consume {con[i]:.1f} msg/s"
        parts.append(
            f'<rect class="hit" x="{x(i) - pw / n / 2:.1f}" y="{MT}" width="{pw / n:.1f}" height="{ph}">'
            f"<title>{tip}</title></rect>"
        )
    svg = "\n".join(parts)
    rows = "\n".join(
        f"<tr><td>{(i + 1) * 10}s</td><td>{pub[i]:.1f}</td><td>{con[i]:.1f}</td></tr>" for i in range(n)
    )
    return f"""<figure class="omb-chart">
  <h3>Publish and consume rate</h3>
  <p class="omb-chart__sub">msg/s per 10-second sample; the workload asks for 500 msg/s</p>
  <ul class="omb-chart__legend"><li class="s1">publish</li><li class="s2">consume</li></ul>
  <svg viewBox="0 0 {W} {H}" role="img" aria-label="Publish and consume rate per 10-second sample">
{svg}
  </svg>
  <details><summary>Show data</summary>
    <table><thead><tr><th>Sample</th><th>Publish</th><th>Consume</th></tr></thead><tbody>
{rows}
    </tbody></table>
  </details>
</figure>"""


PCTS = [("p50", "50pct"), ("p75", "75pct"), ("p95", "95pct"), ("p99", "99pct"),
        ("p99.9", "999pct"), ("p99.99", "9999pct"), ("max", "Max")]


def latency_chart(result):
    pub = [result[f"aggregatedPublishLatency{k}"] for _, k in PCTS]
    e2e = [result[f"aggregatedEndToEndLatency{k}"] for _, k in PCTS]
    lo = min(pub + e2e)
    hi = max(pub + e2e)
    lmin = math.floor(math.log10(lo))
    lmax = math.ceil(math.log10(hi))
    pw, ph = W - ML - MR - 40, H - MT - MB
    n = len(PCTS)

    def x(i):
        return ML + 10 + (i / (n - 1)) * (pw - 10)

    def y(v):
        return MT + ph - (math.log10(v) - lmin) / (lmax - lmin) * ph

    ticks = []
    for e in range(lmin, lmax + 1):
        for m in (1, 2, 5) if lmax - lmin <= 2 else (1,):
            t = m * 10 ** e
            if 10 ** lmin <= t <= 10 ** lmax:
                ticks.append(t)
    parts = ['<g class="grid">']
    for t in ticks:
        parts.append(f'<line x1="{ML}" x2="{ML + pw}" y1="{y(t):.1f}" y2="{y(t):.1f}"/>')
    parts.append('</g><g class="axis">')
    for t in ticks:
        label = f"{t:g}"
        parts.append(f'<text x="{ML - 8}" y="{y(t) + 3:.1f}" text-anchor="end">{label}</text>')
    for i, (name, _) in enumerate(PCTS):
        parts.append(f'<text x="{x(i):.1f}" y="{H - MB + 16}" text-anchor="middle">{name}</text>')
    parts.append(f'<text class="title" x="{ML}" y="{H - 2}">percentile, ms on a log scale</text>')
    parts.append("</g>")
    for cls, data, name in (("s1", pub, "publish"), ("s2", e2e, "end-to-end")):
        d = " ".join(f"{'M' if i == 0 else 'L'}{x(i):.1f},{y(v):.1f}" for i, v in enumerate(data))
        parts.append(f'<path class="line {cls}" d="{d}"/>')
        for i, v in enumerate(data):
            parts.append(
                f'<circle class="hit" cx="{x(i):.1f}" cy="{y(v):.1f}" r="9"><title>{name} {PCTS[i][0]}: {fmt(v)} ms</title></circle>'
                f'<circle class="pt {cls}" cx="{x(i):.1f}" cy="{y(v):.1f}" r="3.5"/>'
            )
    # Direct labels at the p99 point, which is what most readers look for.
    i99 = 3
    a, b = y(pub[i99]), y(e2e[i99])
    above_pub = a <= b
    for cls, v, yy, up in (("s1", pub[i99], a, above_pub), ("s2", e2e[i99], b, not above_pub)):
        dy = -9 if up else 15
        parts.append(f'<text class="lbl" x="{x(i99) - 8:.1f}" y="{yy + dy:.1f}" text-anchor="end">{fmt(v)} ms</text>')
    svg = "\n".join(parts)
    rows = "\n".join(
        f"<tr><td>{name}</td><td>{fmt(pub[i])}</td><td>{fmt(e2e[i])}</td></tr>" for i, (name, _) in enumerate(PCTS)
    )
    return f"""<figure class="omb-chart">
  <h3>Latency percentiles</h3>
  <p class="omb-chart__sub">Aggregated over the measured phase</p>
  <ul class="omb-chart__legend"><li class="s1">publish</li><li class="s2">end-to-end</li></ul>
  <svg viewBox="0 0 {W} {H}" role="img" aria-label="Publish and end-to-end latency by percentile">
{svg}
  </svg>
  <details><summary>Show data</summary>
    <table><thead><tr><th>Percentile</th><th>Publish ms</th><th>End-to-end ms</th></tr></thead><tbody>
{rows}
    </tbody></table>
  </details>
</figure>"""


def render_charts():
    result = json.loads((HERE / "quickstart-result.json").read_text())
    return HEADER + f"""<div class="omb-charts">
{rate_chart(result)}
{latency_chart(result)}
</div>
<p class="omb-caption">From <code>first-result.json</code> of the run above: workload
<code>{html.escape(result["workload"])}</code>, driver <code>{html.escape(result["driver"])}</code>, one laptop, every
container in one Docker VM. These charts show what a result contains; they are not a measurement of Kafka.</p>
"""


def main():
    PARTIALS.mkdir(parents=True, exist_ok=True)
    (PARTIALS / "omb-demo-terminal.html").write_text(render_terminal())
    (PARTIALS / "omb-demo-charts.html").write_text(render_charts())


if __name__ == "__main__":
    main()
